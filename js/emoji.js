const svg = (d) => `<svg class="emi" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><path d="${d}"/></svg>`;

// ключи без вариационного селектора тоже должны совпадать: «☀» и «☀️»
const VS = '️';
const norm = (e) => e.replaceAll(VS, '');
const MAP = new Map(Object.entries(SHAPES).map(([e, d]) => [norm(e), d]));
const escRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const keys = [...MAP.keys()].sort((a, b) => b.length - a.length);
const RE = new RegExp(`(?:${keys.map((k) => [...k].map(escRe).join(`${VS}?`)).join('|')})${VS}?`, 'gu');
const TEST = new RegExp(RE.source, 'u');

export const emojiIcon = (e) => { const d = MAP.get(norm(e)); return d ? svg(d) : e; };

const SKIP = new Set(['SCRIPT', 'STYLE', 'TEXTAREA', 'OPTION', 'SELECT', 'TITLE', 'text', 'tspan']);
const tpl = document.createElement('template');

function iconize(node) {
  if (node.nodeType === 3) {
    const p = node.parentNode;
    if (!p || SKIP.has(p.nodeName) || p.closest?.('svg') || !TEST.test(node.data)) return;
    const html = node.data.replace(/[&<>]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;' }[c])).replace(RE, (m) => emojiIcon(m));
    tpl.innerHTML = html;
    p.replaceChild(tpl.content, node);
    return;
  }
  if (node.nodeType !== 1 || SKIP.has(node.nodeName) || node.nodeName === 'svg') return;
  const w = document.createTreeWalker(node, NodeFilter.SHOW_TEXT);
  const list = [];
  let n = w.nextNode();
  while (n) { if (TEST.test(n.data)) list.push(n); n = w.nextNode(); }
  list.forEach(iconize);
}

export function startEmojiIcons() {
  iconize(document.body);
  new MutationObserver((muts) => {
    for (const m of muts) {
      if (m.type === 'characterData') iconize(m.target);
      else m.addedNodes.forEach(iconize);
    }
  }).observe(document.body, { childList: true, subtree: true, characterData: true });
}
